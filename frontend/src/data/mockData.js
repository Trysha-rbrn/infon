export function getOrganizerById(id, customList = null) {
  if (!id) return null
  const list = customList || organizers
  return (
    list.find((o) => String(o.id) === String(id) || o.shortName?.toLowerCase() === String(id).toLowerCase() || o.name?.toLowerCase() === String(id).toLowerCase()) ||
    organizers.find((o) => String(o.id) === String(id) || o.shortName?.toLowerCase() === String(id).toLowerCase()) ||
    null
  )
}

export function getTypeInfo(type) {
  if (!type) return { value: 'Ostalo', label: 'Događaj', color: '#64748B' }
  const found = eventTypes.find(
    (t) => t.value.toLowerCase() === type.toLowerCase() || type.toLowerCase().includes(t.value.toLowerCase())
  )
  if (found) return found

  // fallback dinamicke lepe boje na osnovu naziva
  if (type.toLowerCase().includes('hakaton')) return { value: type, label: type, color: '#F59E0B' }
  if (type.toLowerCase().includes('takmič') || type.toLowerCase().includes('case')) return { value: type, label: type, color: '#E11D48' }
  if (type.toLowerCase().includes('radionic') || type.toLowerCase().includes('trening')) return { value: type, label: type, color: '#10B981' }
  if (type.toLowerCase().includes('sajam') || type.toLowerCase().includes('info')) return { value: type, label: type, color: '#0EA5E9' }
  if (type.toLowerCase().includes('panel') || type.toLowerCase().includes('tribin')) return { value: type, label: type, color: '#8B5CF6' }
  if (type.toLowerCase().includes('sport')) return { value: type, label: type, color: '#0284C7' }
  if (type.toLowerCase().includes('humanitar')) return { value: type, label: type, color: '#EC4899' }
  if (type.toLowerCase().includes('kulturn') || type.toLowerCase().includes('predstav')) return { value: type, label: type, color: '#F97316' }
  if (type.toLowerCase().includes('simpozij') || type.toLowerCase().includes('nauc')) return { value: type, label: type, color: '#003F7F' }

  return { value: type, label: type, color: '#475569' }
}
